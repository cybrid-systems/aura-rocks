#!/usr/bin/env python3
"""Generate ws/hot.aura: the hot leaf defines that live in the Aura workspace
(set-code + eval-current) so aura-kernel-sink can find, compile and swap them.

The defines are written in the subset lib/vkgen.aura compiles (Int + byte
string "S" params, if/and/or/not, letrec self tail loops, no let).  The block
seek is generated here because the subset has no let: offsets are spelled out
as digit expressions and carried in loop variables, so the Soft body does not
recompute them (no strawman: one OFF/KLEN evaluation per probe step)."""

def D(s, x):
    return f"(- (string-ref {s} {x}) 48)"

def num(s, base, w):
    terms = []
    for i in range(w):
        mul = 10 ** (w - 1 - i)
        d = D(s, f"(+ {base} {i})" if i else base)
        terms.append(d if mul == 1 else f"(* {d} {mul})")
    return "(+ " + " ".join(terms) + ")"

def off_of(m):            # restart array: 6-digit entry offsets at ra
    return num("blk", f"(+ ra (* 6 {m}))", 6)

def klen_of(off):         # entry: type(1) klen(4) vlen(6) key value
    return num("blk", f"(+ {off} 1)", 4)

def narrow(lo, hi):
    m = f"(quotient (+ {lo} {hi}) 2)"
    off = f"(if (< {lo} {hi}) {off_of(m)} 0)"
    # kl needs off; recompute (once per narrowing step, not per byte)
    kl = f"(if (< {lo} {hi}) {klen_of(off_of(m))} 0)"
    return f"(loop {lo} {hi} 0 {off} {kl})"

M = "(quotient (+ lo hi) 2)"
block_seek = f"""(define rk-block-seek
  (lambda (blk key n ra)
    (letrec ((loop (lambda (lo hi j off kl)
       (if (>= lo hi) lo
         (if (or (>= j kl) (>= j (string-length key)))
             (if (< kl (string-length key)) {narrow(f"(+ {M} 1)", "hi")} {narrow("lo", M)})
             (if (< (string-ref blk (+ off 11 j)) (string-ref key j)) {narrow(f"(+ {M} 1)", "hi")}
                 (if (> (string-ref blk (+ off 11 j)) (string-ref key j)) {narrow("lo", M)}
                     (loop lo hi (+ j 1) off kl))))))))
      {narrow("0", "n")})))"""

pow2 = "(if (= (modulo p 6) 0) 1 (if (= (modulo p 6) 1) 2 (if (= (modulo p 6) 2) 4 (if (= (modulo p 6) 3) 8 (if (= (modulo p 6) 4) 16 32)))))"

src = f""";; ws/hot.aura -- GENERATED by tools/gen_hot.py. Do not edit by hand.
;; Hot leaf defines of aura-rocks. Loaded into the Aura workspace by
;; lib/hot.aura (set-code + eval-current); the engine calls them by name, so
;; aura-kernel-sink can swap any of them for a C kernel (mutate:rebind) and
;; roll it back (hot-strategy:heal!) without the engine noticing.

;; Adler-32 of s[start, end).  WAL records and SST blocks.
(define rk-checksum
  (lambda (s start end)
    (letrec ((loop (lambda (i a b)
       (if (< i end)
           (loop (+ i 1) (modulo (+ a (string-ref s i)) 65521) (modulo (+ b (modulo (+ a (string-ref s i)) 65521)) 65521))
           (+ (* b 65536) a)))))
      (loop start 1 0))))

;; 32-bit multiplicative string hash (FNV-style, add instead of xor: Aura has
;; no bitwise ops) with a final avalanche step.  Bloom filter keys.
(define rk-hash
  (lambda (s seed)
    (letrec ((loop (lambda (i h)
       (if (< i (string-length s))
           (loop (+ i 1) (modulo (* (+ h (string-ref s i)) 16777619) 4294967296))
           (modulo (* (+ h (quotient h 32768)) 166022555) 4294967296)))))
      (loop 0 (modulo (+ seed 2166136261) 4294967296)))))

;; Bloom probe: bits is a string of 6-bit digits (char 48 + v), nbits bits,
;; k probes by double hashing (delta = h rotated right by 17).  1 = maybe, 0 = no.
(define rk-bloom-probe
  (lambda (bits nbits h k)
    (letrec ((loop (lambda (i p d)
       (if (>= i k) 1
           (if (= (modulo (quotient (- (string-ref bits (quotient p 6)) 48) {pow2}) 2) 1)
               (loop (+ i 1) (modulo (+ p d) nbits) d)
               0)))))
      (loop 0 (modulo h nbits) (+ (quotient h 131072) (* (modulo h 131072) 32768))))))

;; Fixed-width decimal field s[off, off+w).
(define rk-dec
  (lambda (s off w)
    (letrec ((loop (lambda (i v)
       (if (< i w) (loop (+ i 1) (+ (* v 10) (- (string-ref s (+ off i)) 48))) v))))
      (loop 0 0))))

;; Lower bound in a data block: index of the first entry whose key >= key
;; (n entries, restart array of 6-digit offsets at ra; entry = type(1)
;; klen(4) vlen(6) key value).  Byte-wise compare, carried in loop vars.
{block_seek}

;; Kernel slots: aura-kernel-sink binds sink-kernel-<name> to the C kernel
;; and swaps <name> for a wrapper that calls it (one atomic batch).
(define sink-kernel-rk-checksum 0)
(define sink-kernel-rk-hash 0)
(define sink-kernel-rk-bloom-probe 0)
(define sink-kernel-rk-dec 0)
(define sink-kernel-rk-block-seek 0)

;; Sink control plane (aura-kernel-sink reads it; hot-swappable).
(define (sink-min-speedup) 1.5)
"""
open("ws/hot.aura", "w").write(src)
print("wrote ws/hot.aura", len(src), "bytes")
